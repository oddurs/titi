/**
 * Sequences that become one cell. Overbars in particular arrive as a letter
 * plus a combining mark, which a fixed grid has nowhere to put.
 */
const DIGRAPHS: [string, string][] = [
  ["x\u0304", "\uE000"],
  ["y\u0304", "\uE001"],
  ["\u0233", "\uE001"],
];

/**
 * Subscripts get folded to plain digits — a 5×7 cell has no room for a real
 * subscript, and every device of this vintage writes L1 rather than L₁.
 */
const FOLD: Record<string, string> = {
  "₀": "0", "₁": "1", "₂": "2", "₃": "3", "₄": "4",
  "₅": "5", "₆": "6", "₇": "7", "₈": "8", "₉": "9",
  "ₜ": "T",
  "‑": "-", "–": "-", "—": "-",
  "’": "'", "‘": "'",
  "“": '"', "”": '"',
};

/** Normalise a string for the panel: fold what the ROM can't draw. */
export function foldForDisplay(s: string): string {
  let text = s;
  for (const [from, to] of DIGRAPHS) text = text.split(from).join(to);
  let out = "";
  for (const ch of text) {
    // any stray combining mark has nowhere to go on a fixed grid
    if (ch >= "\u0300" && ch <= "\u036f") continue;
    out += FOLD[ch] ?? ch;
  }
  return out;
}
